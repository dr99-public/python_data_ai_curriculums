

# BASIC IF statement
status = "ACTIVE"

if status == "ACTIVE":
    print("Customer is active.")
else:
    print("Customer is not active.")


# MORE THAN ONE CONDITION if statement: elif ("else if")
balance = 1250.75

if balance >= 1000:
    print("High balance")
elif balance > 0:
    print("Positive balance")
else:
    print("Zero or negative balance")


