
# dictionary is like a list, but it associates a key with each list value
# this is called "key-value pairs"

customer = {
    "customer_id": "C001",
    "status": "ACTIVE",
    "region": "Northeast",
    "balance": 1250.75,
}

print(customer)
print(customer["customer_id"])
print(customer["status"])
print(customer["balance"])

